def extra_repos() -> list[tuple[str, str]]:
    """(repo, language) pairs not already covered by the core list."""

    seen: set[str] = set()
    out: list[tuple[str, str]] = []
    for repo, language in EXTRA_GITHUB_REPOS + LONG_TAIL_GITHUB_REPOS:
        if repo in seen:
            continue
        seen.add(repo)
        out.append((repo, language))
    return out


def source_inventory() -> dict[str, int]:
    """Per-language candidate counts, for the coverage report."""

    counts: dict[str, int] = {}
    for _repo, language in EXTRA_GITHUB_REPOS + LONG_TAIL_GITHUB_REPOS:
        counts[language] = counts.get(language, 0) + 1
    return dict(sorted(counts.items()))
