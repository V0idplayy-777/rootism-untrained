TESTS = '''"""Static site checks: valid structure, no broken local links, no placeholders."""

from __future__ import annotations

from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


class Collector(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.tags: list[str] = []
        self.attrs: list[tuple[str, str, str]] = []

    def handle_starttag(self, tag, attrs):
        self.tags.append(tag)
        for name, value in attrs:
            if value:
                self.attrs.append((tag, name, value))


def parse(name: str = "index.html") -> Collector:
    parser = Collector()
    parser.feed((ROOT / name).read_text(encoding="utf-8"))
    return parser


def test_required_tags():
    page = parse()
    assert "html" in page.tags and "head" in page.tags and "body" in page.tags
    assert page.tags.count("h1") == 1


def test_assets_exist():
    page = parse()
    for tag, name, value in page.attrs:
        if tag == "link" and name == "href" and not value.startswith(("http", "#")):
            assert (ROOT / value).exists(), f"missing stylesheet: {value}"
        if tag == "script" and name == "src":
            assert (ROOT / value).exists(), f"missing script: {value}"


def test_no_unreplaced_placeholders():
    for path in ROOT.glob("*.*"):
        if path.suffix in {".html", ".css", ".js"}:
            text = path.read_text(encoding="utf-8")
            assert "__DISPLAY_NAME__" not in text
            assert "__DESCRIPTION__" not in text
'''


def _tokens(text: str, options: ProjectOptions) -> str:
    return (
        text.replace("__DISPLAY_NAME__", options.display_name)
        .replace("__DESCRIPTION__", options.description or options.display_name)
        .replace("__NAME__", options.name)
    )


def build(options: ProjectOptions) -> dict[str, str]:
    return {
        "index.html": _tokens(INDEX, options),
        "styles.css": STYLES,
        "script.js": SCRIPT,
        "favicon.svg": FAVICON,
        "tests/test_site.py": TESTS,
        ".gitignore": gitignore(),
    }


