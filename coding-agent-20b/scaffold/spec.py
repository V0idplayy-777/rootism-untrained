"""Template contract: what a starter is, what it generates, and how to describe it.

A template is a pure function from :class:`ProjectOptions` to a dict of
``path -> content``. Keeping templates as code (rather than half-rendered
directories) means options like "add auth" or "use Postgres" change the file set
deliberately instead of leaving dead placeholders in the output.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Callable


@dataclass
class ProjectOptions:
    name: str
    display_name: str
    module: str
    description: str = ""
    port: int = 8000
    use_auth: bool = False
    database: str = "sqlite"
    author: str = "you"
    year: str = "2026"
    license: str = "MIT"
    extras: dict[str, str] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)

    @property
    def database_url_env(self) -> str:
        return "DATABASE_URL" if self.database == "postgres" else "SQLITE_PATH"

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "display_name": self.display_name,
            "module": self.module,
            "description": self.description,
            "port": self.port,
            "use_auth": self.use_auth,
            "database": self.database,
            "author": self.author,
            "year": self.year,
            "license": self.license,
        }


@dataclass
class TemplateSpec:
    id: str
    name: str
    tagline: str
    description: str
    stack: str
    kind: str
    tags: list[str] = field(default_factory=list)
    supports_auth: bool = False
    supports_database: bool = False
    default_port: int = 8000
    build: Callable[[ProjectOptions], dict[str, str]] | None = None
    next_steps: list[str] = field(default_factory=list)
    good_for: list[str] = field(default_factory=list)
    run_command: str = ""
    test_command: str = ""
    preview: str = "web"

    def render(self, options: ProjectOptions) -> dict[str, str]:
        if self.build is None:
            raise ValueError(f"template {self.id!r} has no build function")
        files = self.build(options)
        files.setdefault("README.md", self._readme(options))
        return files

    def _readme(self, options: ProjectOptions) -> str:
        auth_line = (
            "\n## Auth\n\nJWT access tokens (HS256) with scrypt password hashing. `POST /auth/register` and\n`POST /auth/login` return a token; protected routes expect `Authorization: Bearer <token>`.\nSet `AUTH_SECRET` in production - the app refuses to boot without it when `APP_ENV=production`.\n"
            if options.use_auth
            else ""
        )
        db_line = (
            "SQLite by default (`data/app.db`); set `DATABASE_URL` to use Postgres instead."
            if options.database == "sqlite"
            else "Postgres via `DATABASE_URL`."
            if options.database == "postgres"
            else "No database in this template."
        )
        return f"""# {options.display_name}

{options.description or self.tagline}

- **Stack:** {self.stack}
- **Generated by:** coding-agent-20b scaffold (`{self.id}`)
- **License:** {options.license}

## Run it

```bash
{self.run_command}
```

Open http://localhost:{options.port} / health at `/healthz`.

## Test it

```bash
{self.test_command}
```

## Deploy it

```bash
agent deploy --dry-run     # see the plan (no account needed)
agent deploy               # build + run, or push to a host
```

The deploy command writes standard `Dockerfile`, `.dockerignore` and
`docker-compose.yml`; nothing generated here needs this agent to run.
{auth_line}
## Data

{db_line}

## Layout

{chr(10).join('- `' + path + '`' for path in sorted(self.build(options))[:12] if path != 'README.md') if self.build else ''}

## Eject

There is nothing to eject from: these are ordinary files using ordinary tools.
Delete `agentdeploy.toml`/`DEPLOY.md` and deploy however you like.
"""

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "name": self.name,
            "tagline": self.tagline,
            "description": self.description,
            "stack": self.stack,
            "kind": self.kind,
            "tags": list(self.tags),
            "supports_auth": self.supports_auth,
            "supports_database": self.supports_database,
            "default_port": self.default_port,
            "good_for": list(self.good_for),
            "run_command": self.run_command,
            "test_command": self.test_command,
            "preview": self.preview,
            "next_steps": list(self.next_steps) or [
                "Read the README for the run/test commands",
                "Generate Docker files with `agent deploy --dry-run`",
                "Run the tests and extend them as you add features",
            ],
        }


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")
    return slug or "app"


def module_name(text: str) -> str:
    name = re.sub(r"[^a-z0-9_]+", "_", (text or "").lower()).strip("_")
    if not name or name[0].isdigit():
        name = f"app_{name}" if name else "app"
    return name


def titleize(text: str) -> str:
    slug = (text or "").replace("_", " ").replace("-", " ").strip()
    return " ".join(word.capitalize() for word in slug.split()) or "New App"


def options_for(template: TemplateSpec, name: str, **overrides) -> ProjectOptions:
    use_auth = bool(overrides.pop("use_auth", False))
    database = overrides.pop("database", None)
    options = ProjectOptions(
        name=slugify(name),
        display_name=titleize(name),
        module=module_name(name),
        port=overrides.pop("port", template.default_port),
        use_auth=use_auth and template.supports_auth,
        database=database or ("sqlite" if template.supports_database else "none"),
        **overrides,
    )
    if not template.supports_auth and use_auth:
        options.warnings.append(f"{template.id} has no auth addon yet; skipping it")
    return options


def find_placeholders(files: dict[str, str]) -> list[str]:
    """Any unreplaced ``{{ placeholder }}`` left in a rendered project."""

    found: list[str] = []
    for path, content in files.items():
        for match in re.finditer(r"\{\{\s*([a-zA-Z0-9_]+)\s*\}\}", content):
            found.append(f"{path}: {match.group(1)}")
    return found
