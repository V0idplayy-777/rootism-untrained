def generate_status_page(
    name: str,
    description: str = "",
    url: str | None = None,
    provider: str = "",
    image: str = "",
    health: dict[str, Any] | None = None,
    deploy_time: str | None = None,
) -> str:
    title = (name or "app").replace("-", " ").title()
    url_html = f'<a href="{_escape(url)}" target="_blank" rel="noopener">{_escape(url)}</a>' if url else "<em>not deployed yet</em>"
    live_button = f'<a class="button" href="{_escape(url)}">Open the app →</a>' if url else ""
    if health is None and url:
        status_badge = '<span class="badge pending">unknown</span>'
        health_html = "not checked"
    elif health and health.get("ok"):
        status_badge = '<span class="badge ok">live</span>'
        health_html = f"ok (status {health.get('status')}, {health.get('attempts', 0)} attempts)"
    elif health:
        status_badge = '<span class="badge fail">unhealthy</span>'
        health_html = f"failed (status {health.get('status')}, {health.get('error', '')})"
    else:
        status_badge = '<span class="badge pending">local only</span>'
        health_html = "—"
    return STATUS_TEMPLATE.format(
        title=_escape(title),
        description=_escape(description or "A project built with CodingAgent-20B."),
        url_html=url_html,
        status_badge=status_badge,
        provider=_escape(provider or "none"),
        deploy_time=_escape(deploy_time or time.strftime("%Y-%m-%d %H:%M:%S")),
        health_html=_escape(str(health_html)),
        image=_escape(image or "—"),
        live_button=live_button,
        date=time.strftime("%Y-%m-%d %H:%M"),
    )


def _escape(text: str) -> str:
    import html
    return html.escape(text or "", quote=True)


def write_status_page(
    root: str | Path,
    name: str,
    description: str = "",
    url: str | None = None,
    provider: str = "",
    image: str = "",
    health: dict[str, Any] | None = None,
) -> str:
    root = Path(root)
    target = root / "status" / "index.html"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        generate_status_page(name, description, url=url, provider=provider, image=image, health=health),
        encoding="utf-8",
    )
    json_path = root / "status" / "status.json"
    json_path.write_text(
        json.dumps(
            {
                "name": name,
                "url": url,
                "provider": provider,
                "image": image,
                "health": health,
                "deployed_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                "ok": bool(health.get("ok")) if health else bool(url),
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return str(target)
