"""Generate production-shaped Docker artifacts from a :class:`ProjectProfile`.

Everything generated here is plain, standard Docker — no proprietary agent
runtime is required to build or run it. The generated images:

* run as a non-root user,
* pin a small base image per detected runtime,
* install dependencies before copying source (layer caching),
* expose a ``HEALTHCHECK`` for server projects (stdlib, no ``curl`` needed),
* read configuration from environment variables, never baked-in secrets.

``write_artifacts()`` writes ``Dockerfile``, ``.dockerignore``,
``docker-compose.yml`` and returns a summary so callers can show the plan.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from .detect import ProjectProfile


@dataclass
class DockerArtifacts:
    dockerfile: str
    dockerignore: str
    compose: str
    image: str
    container_port: int
    notes: list[str] = field(default_factory=list)


def image_name(config_name: str, tag: str = "latest") -> str:
    slug = "".join(ch if ch.isalnum() or ch in "-." else "-" for ch in config_name.lower()).strip("-")
    return f"{slug or 'app'}:{tag}"


def _healthcheck(port: int, path: str) -> str:
    path = path or "/"
    return (
        "HEALTHCHECK --interval=30s --timeout=5s --start-period=20s --retries=3 \\\n"
        f"  CMD python -c \"import urllib.request,sys; "
        f"sys.exit(0 if urllib.request.urlopen('http://127.0.0.1:{port}{path}', timeout=4).status < 500 else 1)\""
    )


def generate_dockerfile(profile: ProjectProfile, config=None) -> str:
    """Return a Dockerfile for the detected project kind."""

    port = int(getattr(config, "port", None) or profile.port or 8000)
    health_path = getattr(config, "health_path", None) or profile.health_path or "/"
    install = profile.install_cmd or ""
    start = profile.start_cmd or ""
    build = profile.build_cmd or ""
    header = (
        f"# syntax=docker/dockerfile:1.6\n"
        f"# Generated by coding-agent-20b (agent deploy). Plain Docker - no lock-in.\n"
        f"# Stack: {profile.language}/{profile.framework}  kind={profile.kind}\n"
    )

    if profile.language == "python":
        python = profile.runtime_version if profile.runtime_version.endswith("-slim") else "3.11-slim"
        is_worker = profile.kind == "worker"
        if profile.kind == "cli":
            return header + f"""FROM python:{python} AS builder
WORKDIR /app
ENV PIP_DISABLE_PIP_VERSION_CHECK=1 PYTHONDONTWRITEBYTECODE=1
COPY requirements.txt* pyproject.toml* setup.py* ./
RUN python -m venv /opt/venv && /opt/venv/bin/pip install --no-cache-dir --upgrade pip \\
 && if [ -f requirements.txt ]; then /opt/venv/bin/pip install --no-cache-dir -r requirements.txt; fi \\
 && if [ -f pyproject.toml ] || [ -f setup.py ]; then /opt/venv/bin/pip install --no-cache-dir .; fi
COPY . .
RUN /opt/venv/bin/pip install --no-cache-dir --no-deps . || true

FROM python:{python}
WORKDIR /app
ENV PATH="/opt/venv/bin:$PATH" PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1
RUN useradd --create-home --uid 10001 appuser
COPY --from=builder /opt/venv /opt/venv
COPY --from=builder --chown=appuser:appuser /app /app
USER appuser
ENTRYPOINT ["python", "-m", "{profile.app_module or 'app'}"]
CMD ["--help"]
"""
        cmd = start or f"python {profile.entrypoint or 'main.py'}"
        # `uvicorn ... --port ${PORT}` forms are already shell-friendly.
        cmd_list = _shell_list(cmd)
        expose = "" if is_worker else f"EXPOSE {port}\n"
        health = "" if is_worker else _healthcheck(port, health_path) + "\n"
        return header + f"""FROM python:{python} AS builder
WORKDIR /app
ENV PIP_DISABLE_PIP_VERSION_CHECK=1 PYTHONDONTWRITEBYTECODE=1
RUN apt-get update && apt-get install -y --no-install-recommends build-essential \\
 && rm -rf /var/lib/apt/lists/*
COPY requirements.txt* pyproject.toml* setup.py* setup.cfg* ./
RUN python -m venv /opt/venv && /opt/venv/bin/pip install --no-cache-dir --upgrade pip \\
 && if [ -f requirements.txt ]; then /opt/venv/bin/pip install --no-cache-dir -r requirements.txt; fi \\
 && if [ -f pyproject.toml ] || [ -f setup.py ]; then /opt/venv/bin/pip install --no-cache-dir .; fi
COPY . .
RUN if [ -f pyproject.toml ] || [ -f setup.py ]; then /opt/venv/bin/pip install --no-cache-dir --no-deps . || true; fi

FROM python:{python}
WORKDIR /app
ENV PATH="/opt/venv/bin:$PATH" PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1 PORT={port}
RUN useradd --create-home --uid 10001 appuser
COPY --from=builder /opt/venv /opt/venv
COPY --from=builder --chown=appuser:appuser /app /app
USER appuser
ENV PYTHONPATH=/app
{expose}{health}CMD {cmd_list}
"""

    if profile.framework == "nextjs":
        node = profile.runtime_version or "20-bookworm-slim"
        return header + f"""FROM node:{node} AS deps
WORKDIR /app
ENV NEXT_TELEMETRY_DISABLED=1
COPY package.json package-lock.json* pnpm-lock.yaml* yarn.lock* ./
RUN {install or 'npm ci'} 

FROM node:{node} AS builder
WORKDIR /app
ENV NEXT_TELEMETRY_DISABLED=1
COPY --from=deps /app/node_modules ./node_modules
COPY . .
RUN {build or 'npm run build'}

FROM node:{node} AS runner
WORKDIR /app
ENV NODE_ENV=production NEXT_TELEMETRY_DISABLED=1 PORT={port}
RUN groupadd --system --gid 10001 nodeapp && useradd --system --uid 10001 --gid nodeapp nodeapp
COPY --from=builder --chown=nodeapp:nodeapp /app ./
USER nodeapp
EXPOSE {port}
{_node_healthcheck(port, health_path)}
CMD {_shell_list(start or 'npm run start')}
"""

    if profile.language == "node" and profile.kind in {"node-web", "worker"}:
        node = profile.runtime_version or "20-bookworm-slim"
        expose = "" if profile.kind == "worker" else f"EXPOSE {port}\n"
        health = "" if profile.kind == "worker" else _node_healthcheck(port, health_path) + "\n"
        build_block = (
            f"RUN {build}\n" if build else ""
        )
        return header + f"""FROM node:{node} AS deps
WORKDIR /app
COPY package.json package-lock.json* pnpm-lock.yaml* yarn.lock* ./
RUN {install or 'npm ci'} 

FROM node:{node} AS builder
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
{build_block}
FROM node:{node} AS runner
WORKDIR /app
ENV NODE_ENV=production PORT={port}
RUN groupadd --system --gid 10001 nodeapp && useradd --system --uid 10001 --gid nodeapp nodeapp
COPY --from=builder --chown=nodeapp:nodeapp /app ./
USER nodeapp
{expose}{health}CMD {_shell_list(start or 'node index.js')}
"""

    if profile.language == "node" and profile.kind == "cli":
        node = profile.runtime_version or "20-bookworm-slim"
        return header + f"""FROM node:{node} AS deps
WORKDIR /app
COPY package.json package-lock.json* pnpm-lock.yaml* yarn.lock* ./
RUN {install or "npm ci --omit=dev"}

FROM node:{node}
WORKDIR /app
ENV NODE_ENV=production
RUN groupadd --system --gid 10001 nodeapp && useradd --system --uid 10001 --gid nodeapp nodeapp
COPY --from=deps --chown=nodeapp:nodeapp /app/node_modules ./node_modules
COPY --chown=nodeapp:nodeapp . .
USER nodeapp
ENTRYPOINT {_shell_list(f"node {profile.entrypoint or 'index.js'}")}
CMD ["--help"]
"""

    if profile.kind == "static":
        node = profile.runtime_version or "20-bookworm-slim"
        build = profile.build_cmd
        static_dir = profile.static_dir or "dist"
        copy_src = (
            f"""FROM node:{node} AS builder
WORKDIR /app
COPY package.json package-lock.json* pnpm-lock.yaml* yarn.lock* ./
RUN {profile.install_cmd or 'npm ci'} 
COPY . .
RUN {build or 'npm run build'}
"""
            if build
            else ""
        )
        source = "COPY --from=builder /app/" + static_dir + " /usr/share/nginx/html\n" if build else f"COPY {static_dir if static_dir != '.' else '.'} /usr/share/nginx/html\n"
        return header + f"""{copy_src}
FROM nginx:1.27-alpine AS runner
COPY nginx.conf /etc/nginx/conf.d/default.conf
{source}RUN chown -R nginx:nginx /usr/share/nginx/html && \\
    sed -i 's/listen       80;/listen       8080;/' /etc/nginx/conf.d/default.conf || true
USER nginx
EXPOSE 8080
HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 \\
  CMD wget -qO- http://127.0.0.1:8080{health_path} >/dev/null || exit 1
"""

    raise ValueError(
        f"cannot generate a Dockerfile for kind={profile.kind!r}; "
        "set [deploy] start_cmd or add your own Dockerfile"
    )


def _node_healthcheck(port: int, path: str) -> str:
    return (
        "HEALTHCHECK --interval=30s --timeout=5s --start-period=20s --retries=3 \\\n"
        f"  CMD node -e \"fetch('http://127.0.0.1:{port}{path or '/'}').then(r=>process.exit(r.status<500?0:1)).catch(()=>process.exit(1))\""
    )


def _shell_list(command: str) -> str:
    """Render a CMD: JSON-exec for simple commands, shell form when it needs one."""

    if any(token in command for token in ("&&", "$", "|", ">")):
        return f"[\"sh\", \"-c\", \"{command.replace(chr(34), chr(92) + chr(34))}\"]"
    parts = command.split()
    return "[" + ", ".join(f'"{p}"' for p in parts) + "]"


def generate_dockerignore(profile: ProjectProfile) -> str:
    lines = [
        "# Generated by agent deploy - keep images small and secrets out",
        ".git",
        ".gitignore",
        ".github",
        ".agent",
        ".venv",
        "venv",
        "env",
        "__pycache__",
        "*.pyc",
        "*.pyo",
        ".pytest_cache",
        ".mypy_cache",
        ".ruff_cache",
        "node_modules",
        ".next",
        ".nuxt",
        "dist",
        "build",
        "coverage",
        ".env",
        ".env.*",
        "!.env.example",
        "*.log",
        "*.sqlite3",
        "*.db",
        "Dockerfile",
        "docker-compose.yml",
        ".DS_Store",
        "tests",
    ]

    if profile.kind == "static":
        lines = [line for line in lines if line != "dist"]
    return "\n".join(lines) + "\n"


def generate_nginx_conf() -> str:
    return """server {
    listen 8080;
    server_name _;
    root /usr/share/nginx/html;
    index index.html;

    gzip on;
    gzip_types text/plain text/css application/javascript application/json image/svg+xml;
    gzip_min_length 1024;

    location /healthz {
        access_log off;
        add_header Content-Type text/plain;
        return 200 "ok\\n";
    }

    location /assets/ {
        expires 1y;
        add_header Cache-Control "public, immutable";
    }

    location / {
        try_files $uri $uri/ /index.html;
    }
}
"""


def generate_compose(profile: ProjectProfile, image: str, config=None) -> str:
    port = int(getattr(config, "port", None) or profile.port or 8000)
    health_path = getattr(config, "health_path", None) or profile.health_path or "/"
    env_names = list(profile.env_required)
    env_lines = "\n".join(f"      {name}: ${{{name}:-}}" for name in env_names)
    health = (
        f"    healthcheck:\n"
        f"      test: [\"CMD-SHELL\", \"python -c \\\"import urllib.request;urllib.request.urlopen('http://127.0.0.1:{port}{health_path}')\\\" || exit 1\"]\n"
        f"      interval: 30s\n      timeout: 5s\n      retries: 3\n      start_period: 20s\n"
        if profile.kind in {"python-web", "node-web", "nextjs"}
        else ""
    )
    ports = f'      - "{port}:{port}"\n' if port else ""
    return f"""# Generated by agent deploy. `docker compose up --build` runs this project
# anywhere Docker runs - your laptop, a VPS, Coolify, Fly, Render or ECS.
services:
  {profile.name or 'app'}:
    build:
      context: .
      dockerfile: Dockerfile
    image: {image}
    restart: unless-stopped
{ports}    environment:
      PORT: "{port}"
{env_lines}
{health}"""


def write_artifacts(
    root: str | Path,
    profile: ProjectProfile,
    config=None,
    *,
    tag: str = "latest",
    force: bool = False,
) -> dict:
    """Write Dockerfile/.dockerignore/docker-compose.yml (never clobbers by default)."""

    root = Path(root)
    name = getattr(config, "name", None) or profile.name
    image = image_name(name, tag)
    written: list[str] = []
    skipped: list[str] = []

    dockerfile = generate_dockerfile(profile, config)
    dockerignore = generate_dockerignore(profile)
    compose = generate_compose(profile, image, config)

    existing = root / "Dockerfile"
    if existing.exists() and not force:
        skipped.append("Dockerfile")
        dockerfile = existing.read_text(encoding="utf-8")
    else:
        existing.write_text(dockerfile, encoding="utf-8")
        written.append("Dockerfile")

    ignore_path = root / ".dockerignore"
    if not ignore_path.exists() or force:
        ignore_path.write_text(dockerignore, encoding="utf-8")
        written.append(".dockerignore")
    else:
        skipped.append(".dockerignore")

    if profile.kind in {"python-web", "node-web", "nextjs"} or profile.kind == "worker":
        compose_path = root / "docker-compose.yml"
        if not compose_path.exists() or force:
            compose_path.write_text(compose, encoding="utf-8")
            written.append("docker-compose.yml")
        else:
            skipped.append("docker-compose.yml")

    if profile.kind == "static" and generated_nginx_needed(root, dockerfile):
        (root / "nginx.conf").write_text(generate_nginx_conf(), encoding="utf-8")
        written.append("nginx.conf")

    notes: list[str] = []
    if skipped:
        notes.append("kept existing: " + ", ".join(skipped))
    return {
        "written": written,
        "skipped": skipped,
        "image": image,
        "port": int(getattr(config, "port", None) or profile.port or 8000),
        "notes": notes,
    }


def generated_nginx_needed(root: Path, dockerfile: str) -> bool:
    return "nginx.conf" in dockerfile and not (root / "nginx.conf").exists()
