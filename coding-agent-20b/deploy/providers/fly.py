"""Fly.io provider via the official ``flyctl`` CLI.

``flyctl`` is the documented way to script Fly; re-implementing the Machines
GraphQL API here would be more fragile, not less locked-in (fly.toml is standard
and portable). If ``flyctl`` is missing the provider says so and the engine can
fall back to another target.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

from ..health import wait_for_http
from ..plan import DeployStep, ProviderResult
from .base import Availability, DeployContext, DeployProvider


def generate_fly_toml(ctx: DeployContext) -> str:
    app = ctx.config.name
    port = ctx.port
    return f"""# Generated by agent deploy - standard fly.toml, keep or edit freely.
app = "{app}"
primary_region = "{ctx.config.region or 'iad'}"

[build]
  dockerfile = "Dockerfile"

[env]
  PORT = "{port}"

[http_service]
  internal_port = {port}
  force_https = true
  auto_stop_machines = "stop"
  auto_start_machines = true
  min_machines_running = 0

  [[http_service.checks]]
    grace_period = "20s"
    interval = "30s"
    method = "GET"
    path = "{ctx.health_path}"
    timeout = "5s"
"""


class FlyProvider(DeployProvider):
    name = "fly"
    label = "Fly.io (flyctl)"
    requires_token = True
    supports_kinds = ("python-web", "node-web", "nextjs", "worker")

    def available(self, ctx: DeployContext) -> Availability:
        binary = shutil.which("flyctl") or shutil.which("fly")
        if not binary:
            return Availability(
                ok=False,
                reason="flyctl is not installed",
                fix="curl -L https://fly.io/install.sh | sh  (then `fly auth login`)",
            )
        if not ctx.token("fly"):
            code, output = self.run([binary, "auth", "whoami"], ".", timeout=30)
            if code != 0:
                return Availability(
                    ok=False,
                    reason="flyctl is not authenticated",
                    fix="fly auth login, or export FLY_API_TOKEN=...",
                )
        return Availability(ok=True, reason=f"{binary}")

    def steps(self, ctx: DeployContext) -> list[DeployStep]:
        return [
            DeployStep("config", "Write fly.toml (app name, internal port, health check)", "", "build"),
            DeployStep("launch", "Create the Fly app if it does not exist", "flyctl launch --no-deploy", "release"),
            DeployStep("deploy", "Build remotely and release", "flyctl deploy --remote-only", "release"),
            DeployStep("health", "Check https://<app>.fly.dev", ctx.health_path, "health"),
        ]

    def deploy(self, ctx: DeployContext) -> ProviderResult:
        binary = shutil.which("flyctl") or shutil.which("fly") or "flyctl"
        cfg = Path(ctx.root) / "fly.toml"
        if not cfg.exists():
            cfg.write_text(generate_fly_toml(ctx), encoding="utf-8")
        env = {"FLY_API_TOKEN": ctx.token("fly")} if ctx.token("fly") else {}
        if ctx.dry_run:
            return ProviderResult(ok=True, public=True, detail="dry run: wrote fly.toml", steps=self.steps(ctx))

        code, output = self.run(
            [binary, "launch", "--no-deploy", "--yes", "--name", ctx.config.name, "--region", ctx.config.region or "iad"],
            ctx.root,
            timeout=300,
            env=env,
        )
        # "app already exists" is fine; anything else fatal stops here.
        if code != 0 and "already exists" not in output.lower() and "taken" not in output.lower():
            return ProviderResult(
                ok=False,
                error=f"flyctl launch failed: {output.strip()[-400:]}",
                logs=[output[-3000:]],
                steps=self.steps(ctx),
            )

        code, output = self.run([binary, "deploy", "--remote-only", "--yes"], ctx.root, timeout=max(ctx.timeout, 1200), env=env)
        if code != 0:
            return ProviderResult(
                ok=False,
                error=f"flyctl deploy failed: {output.strip()[-400:]}",
                logs=[output[-4000:]],
                steps=self.steps(ctx),
            )

        url = f"https://{ctx.config.name}.fly.dev"
        match = re.search(r"https://[a-z0-9.\-]+\.fly\.dev", output)
        if match:
            url = match.group(0)
        health = wait_for_http(url + ctx.health_path, client=ctx.client(), timeout=min(ctx.timeout, 180), interval=5)
        return ProviderResult(
            ok=health.ok,
            url=url,
            health_url=url + ctx.health_path,
            public=True,
            detail="released with flyctl",
            error="" if health.ok else health.detail,
            logs=[output[-2000:]],
            steps=self.steps(ctx),
            meta={"health": health.to_dict()},
        )
